#!/usr/bin/env python3
"""Render docs/models/index.md and one page per aircraft.

Sources (all generated by tools/fetch_catalog.py + tools/extract_*):
  data/models_index.json   repo, display name, model package, livery list
  data/model_textures.json  glTF files + every baseColor texture the model references
  data/livery_files.json    a real official livery package per aircraft (what a repaint replaces)
"""
from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT = ROOT / "docs" / "models"
OUT.mkdir(parents=True, exist_ok=True)

idx = json.loads((DATA / "models_index.json").read_text(encoding="utf-8"))
tex = json.loads((DATA / "model_textures.json").read_text(encoding="utf-8"))
liv = json.loads((DATA / "livery_files.json").read_text(encoding="utf-8"))
shared_path = DATA / "shared_files.json"
shared = json.loads(shared_path.read_text(encoding="utf-8")) if shared_path.is_file() else {}

# Materials that are not part of the airframe: cockpit, glass, pilots, interior
NON_AIRFRAME = ("glass", "cockpit", "pilot", "interior", "seat", "screen", "display", "panel", "hud")


def slug(repo: str) -> str:
    return repo.replace("infiniteflight-aircraft-", "")


def livery_dir(path: str | None) -> str:
    if not path:
        return "?"
    return path.rstrip("/").rsplit("/", 1)[-1]


def human(n: int | None) -> str:
    if not n:
        return "-"
    if n >= 1 << 20:
        return f"{n / 1048576:.1f} MB"
    return f"{n / 1024:.0f} KB"


def pipeline(paint: list[dict]) -> tuple[str, str]:
    names = [f["name"] for f in paint]
    if any(n.endswith("_albd.webp") for n in names):
        return ("Modern (per-part albedo)",
                "Each body part carries its own `<Part>_albd.webp` at 4096x4096; the paired "
                "`_comp` / `_norm` / `_emis` files stay as shipped.")
    if len(names) == 1 and names[0].lower() == "texture.webp":
        return ("Legacy (single texture)",
                "One 2048x2048 baseColor image. Replace it together with `Texture_ORM.webp` and "
                "`Texture_N.webp`, or the fuselage renders as black chrome.")
    if len(names) == 1:
        return ("Legacy (single named texture)",
                f"One baseColor image under a model-specific name (`{names[0]}`).")
    if len(names) <= 3:
        return ("Few-part (legacy shading)",
                f"{len(names)} baseColor images, one per body area, each its own PBR material.")
    return ("Multi-part (legacy shading)",
            f"{len(names)} baseColor images across fuselage, wings, engines, gear and details — each a "
            "separate PBR material, so a partial repaint shows up as a patchwork.")


def is_legacy_fillable(f: dict) -> bool:
    """Texture_ORM.webp / Texture_N.webp are exactly what --fill-orm / --fill-normal synthesise."""
    return f["name"] in ("Texture_ORM.webp", "Texture_N.webp")


def advice_for(f: dict) -> str:
    kind = f.get("kind")
    name = f["name"].lower()
    if kind == "orm" or name.endswith("_orm.webp"):
        return "solid `(255,200,0)` - no occlusion, fully rough, non-metal"
    if kind == "normal" or name.endswith("_norm.webp") or name.endswith("_n.webp"):
        return "solid `(128,128,255)` - flat normal"
    if kind == "composite" or name.endswith("_comp.webp"):
        return "ship the official file unchanged; it carries the metal/rough mask"
    if kind == "emissive" or name.endswith("_emis.webp") or name.endswith("_e.webp"):
        return "ship as-is unless you want glowing panels"
    if "original" in name:
        return "optional - the vendor keeps the full-resolution original here"
    return "your artwork"


def explicit_cmd(repo: str, paint: list[dict], extras: list[dict], legacy_fillable: bool) -> str:
    """A copy-pasteable command. No inline comments: `#` inside a backslash continuation breaks bash.

    `extras` here must already be the *required* companions only - optional entries such as the
    vendor's full-resolution `Texture_Original.webp` differ in size and would trip the dimension check.
    """
    ind = "  "
    lines = [
        "python tools/build_slip_package.py \\",
        f"{ind}--platform android \\",
        f"{ind}--aircraft-repo {repo} \\",
        f'{ind}--livery-dir "<a directory from the table above>" \\',
    ]
    for f in list(paint) + list(extras):
        stem = f["name"].rsplit(".", 1)[0]
        lines.append(f'{ind}--texture "{f["name"]}=art/{stem}.png" \\')
    if legacy_fillable:
        lines.append(f"{ind}--fill-orm --fill-normal \\")
    lines.append(f"{ind}--out out/{slug(repo)}.zip")
    return "\n".join(lines)


def auto_cmd(repo: str, paint: list[dict], extras: list[dict], legacy_fillable: bool) -> str:
    ind = "  "
    lines = [
        "python tools/build_slip_package.py --auto --art art/ \\",
        f"{ind}--platform android \\",
        f"{ind}--aircraft-repo {repo} \\",
        f'{ind}--livery-dir "<a directory from the table above>" \\',
    ]
    if legacy_fillable:
        lines.append(f"{ind}--fill-orm --fill-normal \\")
    lines.append(f"{ind}--out out/{slug(repo)}.zip")
    return "\n".join(lines)


def verify_hint(plabel: str) -> list[str]:
    if plabel.startswith("Legacy (single texture)"):
        return [
            "If only the baseColor had been replaced the fuselage would render as black chrome - so the",
            "fact that it looks clean proves the ORM and normal companions are present. A dark, mirror-like",
            "hull means one of the three did not land.",
        ]
    if plabel.startswith("Modern"):
        return [
            "Every part is a separate material: a correct repaint shows **all** listed albedo files changed.",
            "One part still in official colours means that `M_*_albd.webp` entry is missing from the archive.",
            "Do not touch the `_comp` files - they carry the metallic/roughness mask and are what stop the",
            "fuselage from turning into a mirror.",
        ]
    return [
        "Each listed file is its own material, so the repaint is all-or-nothing per part: a wing still in",
        "official colours means `wing_*.webp` did not land, a dark hull means the `_ORM` partner is missing.",
    ]


rows = []
matrix = []
kinds_counter: Counter[str] = Counter()

for repo in sorted(idx):
    info = idx[repo]
    name = info.get("name") or repo
    tinfo = tex.get(repo) or {}
    linfo = liv.get(repo) or {}
    files = sorted(linfo.get("files") or [], key=lambda f: f["name"].lower())
    gltf = tinfo.get("gltf") or []
    base_colors = tinfo.get("baseColor") or []
    base_set = set(base_colors)
    liveries = info.get("liveries") or []
    generic = info.get("genericLiveries") or []
    cfg = info.get("configuration") or {}
    sample = linfo.get("sample") or {}

    everything = files or (shared.get(repo) or {}).get("files") or [
        {"name": n, "size": None, "bytes": None, "kind": "?"} for n in base_colors
    ]
    ktx2_only = bool(everything) and all(f["name"].lower().endswith(".ktx2") for f in everything)
    placeholder_only = (
        len(everything) == 1 and "placeholder" in everything[0]["name"].lower()
    )
    if placeholder_only:
        # The vendor package carries a single placeholder image, so fall back to what the model
        # actually reads - the baseColor set from its glTF.
        everything = [
            {"name": n, "size": None, "bytes": None, "kind": "?"}
            for n in base_colors if not any(k in n.lower() for k in NON_AIRFRAME)
        ]
        inv_source = "placeholder"
    elif files:
        inv_source = "livery"
    elif (shared.get(repo) or {}).get("files"):
        inv_source = "shared"
    else:
        inv_source = "gltf"
    paint = [
        f for f in everything
        if (f["name"] in base_set or f.get("kind") == "albedo")
        and not any(k in f["name"].lower() for k in NON_AIRFRAME)
    ]
    if not paint:
        paint = [f for f in everything if not any(k in f["name"].lower() for k in NON_AIRFRAME)] or everything
    extras = [f for f in everything if f not in paint]
    paint_names = {f["name"] for f in paint}

    plabel, ptext = pipeline(paint)
    kinds_counter[plabel] += 1

    dirs_named = sorted(
        {(l.get("name") or "?", livery_dir(l.get("path"))) for l in liveries if l.get("path")},
        key=lambda x: x[1].lower(),
    )

    lines: list[str] = [
        f"# {name} — `{repo}`",
        "",
        "[← all aircraft](index.md)",
        "",
        "| field | value |",
        "|---|---|",
        f"| Repository name | `{repo}` |",
        f"| Model path in package | `{info.get('path') or '-'}` |",
        f"| Model package | `{info.get('modelPackageId')}` v{info.get('modelVersion')} · {human(info.get('modelSizeBytes'))} |",
        f"| glTF files | {len(gltf)} |",
        f"| Texture pipeline | **{plabel}** |",
        f"| BaseColor images to paint | {len(paint)} |",
        f"| Entries in the official livery package | {len(everything)} |",
        f"| Livery packages | {len(liveries)} named + {len(generic)} generic |",
    ]
    if cfg:
        lines.append(f"| Configuration package | `{cfg.get('packageId')}` · {human(cfg.get('sizeBytes'))} |")
    if sample.get("name"):
        lines.append(f"| Sample livery parsed | {sample['name']} → `{sample.get('path')}`"
                     f"{' (Pro-only)' if sample.get('isProOnly') else ''} |")
    lines += ["", f"> {ptext}", ""]

    # 1. inventory
    lines += ["## 1. Inventory of one official package", ""]
    if ktx2_only:
        lines.append("> **KTX2 pipeline - not writable by this tool.** Every texture this aircraft loads is")
        lines.append("> `.ktx2`. The packager writes WebP/PNG bytes, which the renderer will not accept under")
        lines.append("> these file names. The inventory and the commands below document the file set and the")
        lines.append("> target paths; you have to encode KTX2 yourself (`basisu -ktx2`, or the KTX-Software")
        lines.append("> `ktx create`) and drop the result in by a route that preserves the bytes.")
        lines.append("")
    if inv_source == "livery":
        lines.append("These are the exact entries that livery package ships, at their real dimensions. The")
        lines.append("`paint` column marks the baseColor images — the ones you actually draw. Everything")
        lines.append("else is a PBR companion (`_ORM`, `_comp`, `_norm`, `_emis`) that must be present so the")
        lines.append("material does not fall back to a default channel value.")
    elif inv_source == "shared":
        lines.append("The per-livery package for this aircraft is metadata-only, so the inventory comes from")
        lines.append("the aircraft's shared texture set (`AircraftSharedLiveryFiles`) — the complete file list")
        lines.append("for the airframe, with real dimensions.")
    elif inv_source == "placeholder":
        lines.append("The only package this aircraft ships contains **a single 704x396 placeholder image** — it")
        lines.append("is not a usable livery. The inventory below is therefore the `baseColor` set its glTF")
        lines.append("actually reads, which is what a repaint has to overwrite. Dimensions are not recorded")
        lines.append("for these entries; take them from the model's own textures.")
    else:
        lines.append("No livery package could be parsed for this aircraft, so the inventory is the model's")
        lines.append("own `baseColor` reference set taken from its glTF. Dimensions are not available here.")
    lines += ["", "| file | dimensions | bytes | role | paint |", "|---|---|---|---|---|"]
    for f in sorted(everything, key=lambda x: x["name"].lower()):
        size = f.get("size")
        dim = f"{size[0]}×{size[1]}" if size else "?"
        mark = "**yes**" if f["name"] in paint_names else "keep"
        lines.append(f"| `{f['name']}` | {dim} | {human(f.get('bytes'))} | {f.get('kind')} | {mark} |")
    lines.append("")

    # 2. every baseColor
    lines += ["## 2. Every baseColor texture the model references", "",
              f"The {len(gltf)} glTF file(s) reference {len(base_colors)} distinct baseColor images in total.",
              "Cockpit, glass, pilot and interior materials are included here for completeness — repainting",
              "them changes the cockpit, not the airframe.", "", "```"]
    lines += base_colors or ["(none recorded)"]
    lines += ["```", ""]

    if gltf:
        lines += ["## 3. glTF files inside the model package", "", "```"]
        lines += gltf
        lines += ["```", ""]

    # 4. directories
    lines += [f"## 4. Livery directories ({len(dirs_named)})", "",
              "The directory name is `Path.GetFileName(LiveryPackage.Path)` — **not** what the app shows.",
              ""]
    if dirs_named:
        lines += ["| shown as | directory on disk |", "|---|---|"]
        for display, directory in dirs_named:
            lines.append(f"| {display} | `{directory}` |")
        if generic:
            lines += ["", "Generic packages: " + ", ".join(
                f"{g.get('name')} → `{livery_dir(g.get('path'))}`" for g in generic)]
    else:
        lines.append("No named liveries ship with this aircraft; only the Generic package exists.")
    lines.append("")

    # 5. package - a per-aircraft recipe, not a template
    # The legacy single-texture material always reads Texture_ORM / Texture_N, whether or not the
    # official livery package happens to ship them, so those two get synthesised.
    legacy_fillable = any(f["name"] == "Texture.webp" for f in paint)
    is_optional = lambda f: "original" in f["name"].lower()
    optional_extras = [f for f in extras if is_optional(f)]
    required_extras = [f for f in extras if not is_optional(f)]

    lines += ["## 5. Package it", ""]
    lines.append(f"**Format: {plabel}.** {ptext}")
    lines.append("")
    lines.append("### Files this aircraft needs")
    lines.append("")
    lines.append("| file | dimensions | role | what to put there |")
    lines.append("|---|---|---|---|")
    for f in paint + required_extras + optional_extras:
        size = f.get("size")
        dim = f"{size[0]}x{size[1]}" if size else "?"
        if f in paint:
            mark = "**paint**"
        elif is_optional(f):
            mark = "optional"
        else:
            mark = "keep"
        lines.append(f"| `{f['name']}` | {dim} | {f.get('kind') or '?'} / {mark} | {advice_for(f)} |")
    lines.append("")
    if optional_extras:
        lines.append("The *optional* rows are not part of the command below: they are the vendor's own")
        lines.append("full-resolution copies, they do not match the working resolution, and nothing reads them")
        lines.append("at runtime. Include them only if you deliberately want to overwrite them.")
        lines.append("")
    lines.append("### Option A - explicit list (copy and run)")
    lines.append("")
    lines.append("```bash")
    lines.append(explicit_cmd(repo, paint, required_extras, legacy_fillable))
    lines.append("```")
    lines.append("")
    lines.append("### Option B - auto mode")
    lines.append("")
    lines.append("```bash")
    lines.append(auto_cmd(repo, paint, required_extras, legacy_fillable))
    lines.append("```")
    lines.append("")
    stems = sorted({f["name"].rsplit(".", 1)[0] for f in paint + required_extras})
    lines.append("`--auto` reads `data/livery_files.json`, then looks for these stems in `art/`")
    lines.append("(`.png`, `.webp`, `.jpg` are all accepted):")
    lines.append("")
    lines.append("```")
    for s in stems:
        lines.append(f"{s}.png")
    lines.append("```")
    lines.append("")
    if legacy_fillable:
        lines.append("`--fill-orm --fill-normal` synthesises the two PBR companions at the right size, so you do")
        lines.append("not have to paint them. Drop the flags if you supply your own.")
        lines.append("")
    if required_extras:
        lines.append("### Option C - reuse the companions from an official package")
        lines.append("")
        lines.append("The `keep` rows above are not artwork: they are masks the vendor ships. Rather than")
        lines.append("recreating them, pull them out of an official livery package:")
        lines.append("")
        lines.append("```bash")
        lines.append(f"python tools/fetch_catalog.py --download --type AircraftLivery \\")
        lines.append(f"  --match {slug(repo)} --out dl/")
        lines.append(f"python tools/build_slip_package.py \\")
        lines.append(f"  --platform android \\")
        lines.append(f"  --aircraft-repo {repo} \\")
        lines.append(f'  --livery-dir "<a directory from the table above>" \\')
        for f in paint:
            stem = f["name"].rsplit(".", 1)[0]
            lines.append(f'  --texture "{f["name"]}=art/{stem}.png" \\')
        lines.append(f"  --keep-from dl/<downloaded package>.zip \\")
        lines.append(f"  --out out/{slug(repo)}.zip")
        lines.append("```")
        lines.append("")
        lines.append("`--keep-from` copies every entry in that archive **except** the albedo files, so your own")
        lines.append("artwork always wins and the companions stay byte-identical to the vendor's.")
        lines.append("")
    lines.append("### Where the entries land")
    lines.append("")
    lines.append("```")
    lines.append(f"android: ../../files/aircraft/{repo}/liveries/<directory>/<file>.webp")
    lines.append(f"ios:     ../../Library/dlc/aircraft/{repo}/liveries/<directory>/<file>.webp")
    lines.append("```")
    lines.append("")
    lines.append("`<directory>` must come from the table in section 4 - the folder name, not the name the app")
    lines.append("shows.")
    lines.append("")
    lines.append("### How to tell it worked")
    lines.append("")
    for hint in verify_hint(plabel):
        lines.append(hint)
    lines.append("")

    # 6. import
    lines += ["## 6. Import", "", "```bash",
              f"adb push out/{slug(repo)}.zip /sdcard/Download/{slug(repo)}.zip",
              'adb shell "pm trim-caches <bytes>"   # only when repainting the same directory again',
              "```", "",
              "Then: **Scenery Editor → open an airport → Satellite → Import Imagery** → pick the zip,",
              "force-stop the app, reopen. Full walkthrough: [build-and-import.md](../build-and-import.md).",
              ""]

    (OUT / f"{slug(repo)}.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    rows.append((repo, name, plabel, len(paint), len(liveries), len(gltf), len(everything)))

    dims = sorted({f"{f['size'][0]}x{f['size'][1]}" for f in everything if f.get("size")})
    notes = []
    if legacy_fillable:
        notes.append("three files or black chrome")
    if ktx2_only:
        notes.append("**KTX2 only** - needs an external encoder")
    if inv_source == "placeholder":
        notes.append("inventory is a placeholder; using glTF references")
    if any(f["name"].lower().endswith(".ktx2") for f in everything):
        notes.append("contains .ktx2 entries")
    if inv_source == "shared":
        notes.append("inventory from the shared texture set")
    elif inv_source == "gltf":
        notes.append("inventory from glTF references only")
    matrix.append((name, slug(repo), plabel, len(paint), len(everything),
                   " / ".join(dims) or "?", "; ".join(notes) or "-"))

# ---------- index ----------
lines = [
    "# Aircraft index",
    "",
    f"{len(rows)} aircraft, every one parsed from the live package catalog: its model package",
    "(for the glTF texture references) and one of its official livery packages (for the file",
    "inventory and dimensions). Nothing in these pages is inferred from a file name.",
    "",
    "| aircraft | repo | pipeline | paint | liveries | glTF | pkg entries |",
    "|---|---|---|---|---|---|---|",
]
for repo, name, plabel, npaint, nlivery, ngltf, nentries in rows:
    lines.append(f"| [{name}]({slug(repo)}.md) | `{slug(repo)}` | {plabel} | {npaint} | {nlivery} | {ngltf} | {nentries} |")

lines += ["", "## Pipeline breakdown", ""]
for kind, count in kinds_counter.most_common():
    lines.append(f"- **{kind}** — {count} aircraft")

lines += [
    "",
    "## Regenerate this data",
    "",
    "```bash",
    "python tools/fetch_catalog.py --dump-json data/catalog.json",
    "python tools/extract_models.py --catalog data/catalog.json",
    "python tools/extract_liveries.py --catalog data/catalog.json --type AircraftLivery --pick largest",
    "python tools/build_docs.py",
    "```",
    "",
    "`--pick largest` matters: many per-livery packages are 0-byte metadata-only updates, so picking the",
    "smallest one yields an empty inventory. See [../data-provenance.md](../data-provenance.md).",
    "",
]
(OUT / "index.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

# ---------- packaging matrix ----------
m = [
    "# Packaging matrix",
    "",
    f"All {len(matrix)} aircraft side by side: the format, how many files the official livery package",
    "ships for it, how many of those you actually paint, the dimensions its model expects, and the trap",
    "specific to that format. Every row links to the full page with both copy-and-run commands.",
    "",
    "| aircraft | page | format | files | paint | dimensions | notes |",
    "|---|---|---|---|---|---|---|",
]
for name, slug_, fmt, npaint, nfile, dims, note in matrix:
    m.append(f"| {name} | [`{slug_}`]({slug_}.md) | {fmt} | {nfile} | {npaint} | {dims} | {note} |")

m += [
    "",
    "## The formats, and what changes between them",
    "",
    "**Legacy (single texture)** - one 2048x2048 baseColor image. `Texture.webp` ships alone but the",
    "material also reads `Texture_ORM.webp` (metal/roughness/occlusion) and `Texture_N.webp` (normal).",
    "Replace the baseColor without those two and the hull renders as black chrome. The tool's",
    "`--fill-orm --fill-normal` synthesises both at the right dimensions.",
    "",
    "**Legacy (single named texture)** - the same shape under a model-specific name: `texture.webp`,",
    "`744GEN.webp`, `B717.webp`, `c17.webp`, `SR22.webp`, `767AME.webp`. Same three-file rule, different",
    "stem, so `--fill-orm --fill-normal` does **not** apply - supply the `_ORM` companion the official",
    "package ships, or accept slightly wrong shading.",
    "",
    "**Modern (per-part albedo)** - A320neo and A321neo. One `<Part>_albd.webp` per body part at",
    "4096x4096, each paired with a `_comp.webp` carrying the metal/roughness mask. You paint only the",
    "`_albd` files; the `_comp` files must ship unchanged or the parts stop matching each other. Miss",
    "one albedo and that part stays in official colours.",
    "",
    "**Few-part / Multi-part (legacy shading)** - the majority: fuselage, wings, engines, gear and tail",
    "as separate materials under names like `fuselage_front`, `wing_lh`, `b757_tail`, `b777_200er_uv5`.",
    "Naming is per-aircraft and not derivable - take the list from the page. A partial repaint shows as a",
    "patchwork, and any part left dark is missing its `_ORM` partner.",
    "",
    "## Commands are per aircraft",
    "",
    "Do not copy the A320 command to another type. The `--texture` list is the aircraft's own inventory:",
    "a C172 needs five differently named part files, an A321neo needs eleven, an A320 needs one plus two",
    "synth companions. The exact list is in each page's section 5, and `--auto` reads it from",
    "`data/livery_files.json` so you only supply artwork with matching stems.",
    "",
]
(OUT / "packaging-matrix.md").write_text("\n".join(m) + "\n", encoding="utf-8")

print(f"wrote {len(rows)} aircraft pages + index.md + packaging-matrix.md")
print("pipelines:", dict(kinds_counter))
