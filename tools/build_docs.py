#!/usr/bin/env python3
"""Render docs/models/index.md and one page per aircraft.

Sources (all generated by tools/fetch_catalog.py + tools/extract_*):
  data/models_index.json   repo, display name, model package, livery list
  data/model_textures.json  glTF files + every baseColor texture the model references
  data/livery_files.json    a real official livery package per aircraft (what a repaint replaces)
"""
from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT = ROOT / "docs" / "models"
OUT.mkdir(parents=True, exist_ok=True)

idx = json.loads((DATA / "models_index.json").read_text(encoding="utf-8"))
tex = json.loads((DATA / "model_textures.json").read_text(encoding="utf-8"))
liv = json.loads((DATA / "livery_files.json").read_text(encoding="utf-8"))
shared_path = DATA / "shared_files.json"
shared = json.loads(shared_path.read_text(encoding="utf-8")) if shared_path.is_file() else {}

# Materials that are not part of the airframe: cockpit, glass, pilots, interior
NON_AIRFRAME = ("glass", "cockpit", "pilot", "interior", "seat", "screen", "display", "panel", "hud")


def slug(repo: str) -> str:
    return repo.replace("infiniteflight-aircraft-", "")


def livery_dir(path: str | None) -> str:
    if not path:
        return "?"
    return path.rstrip("/").rsplit("/", 1)[-1]


def human(n: int | None) -> str:
    if not n:
        return "-"
    if n >= 1 << 20:
        return f"{n / 1048576:.1f} MB"
    return f"{n / 1024:.0f} KB"


def pipeline(paint: list[dict]) -> tuple[str, str]:
    names = [f["name"] for f in paint]
    if any(n.endswith("_albd.webp") for n in names):
        return ("Modern (per-part albedo)",
                "Each body part carries its own `<Part>_albd.webp` at 4096x4096; the paired "
                "`_comp` / `_norm` / `_emis` files stay as shipped.")
    if len(names) == 1 and names[0].lower() == "texture.webp":
        return ("Legacy (single texture)",
                "One 2048x2048 baseColor image. Replace it together with `Texture_ORM.webp` and "
                "`Texture_N.webp`, or the fuselage renders as black chrome.")
    if len(names) == 1:
        return ("Legacy (single named texture)",
                f"One baseColor image under a model-specific name (`{names[0]}`).")
    if len(names) <= 3:
        return ("Few-part (legacy shading)",
                f"{len(names)} baseColor images, one per body area, each its own PBR material.")
    return ("Multi-part (legacy shading)",
            f"{len(names)} baseColor images across fuselage, wings, engines, gear and details — each a "
            "separate PBR material, so a partial repaint shows up as a patchwork.")


def paint_cmd(repo: str, paint: list[dict], extras: list[dict], platform: str = "android") -> str:
    ind = "  "
    lines = [
        "python tools/build_slip_package.py \\",
        f"{ind}--platform {platform} \\",
        f"{ind}--aircraft-repo {repo} \\",
        f'{ind}--livery-dir "<livery directory>" \\',
    ]
    for f in paint:
        lines.append(f'{ind}--texture "{f["name"]}=art/{f["name"].replace(".webp", ".png")}" \\')
    if extras:
        lines.append(f"{ind}# ship these unchanged (a solid fill also works) \\")
        for f in extras:
            lines.append(f'{ind}--texture "{f["name"]}=art/{f["name"].replace(".webp", ".png")}" \\')
    lines.append(f"{ind}--out out/{slug(repo)}.zip")
    return "\n".join(lines)


rows = []
kinds_counter: Counter[str] = Counter()

for repo in sorted(idx):
    info = idx[repo]
    name = info.get("name") or repo
    tinfo = tex.get(repo) or {}
    linfo = liv.get(repo) or {}
    files = sorted(linfo.get("files") or [], key=lambda f: f["name"].lower())
    gltf = tinfo.get("gltf") or []
    base_colors = tinfo.get("baseColor") or []
    base_set = set(base_colors)
    liveries = info.get("liveries") or []
    generic = info.get("genericLiveries") or []
    cfg = info.get("configuration") or {}
    sample = linfo.get("sample") or {}

    everything = files or (shared.get(repo) or {}).get("files") or [
        {"name": n, "size": None, "bytes": None, "kind": "?"} for n in base_colors
    ]
    if files:
        inv_source = "livery"
    elif (shared.get(repo) or {}).get("files"):
        inv_source = "shared"
    else:
        inv_source = "gltf"
    paint = [
        f for f in everything
        if (f["name"] in base_set or f.get("kind") == "albedo")
        and not any(k in f["name"].lower() for k in NON_AIRFRAME)
    ]
    if not paint:
        paint = [f for f in everything if not any(k in f["name"].lower() for k in NON_AIRFRAME)] or everything
    extras = [f for f in everything if f not in paint]
    paint_names = {f["name"] for f in paint}

    plabel, ptext = pipeline(paint)
    kinds_counter[plabel] += 1

    dirs_named = sorted(
        {(l.get("name") or "?", livery_dir(l.get("path"))) for l in liveries if l.get("path")},
        key=lambda x: x[1].lower(),
    )

    lines: list[str] = [
        f"# {name} — `{repo}`",
        "",
        "[← all aircraft](index.md)",
        "",
        "| field | value |",
        "|---|---|",
        f"| Repository name | `{repo}` |",
        f"| Model path in package | `{info.get('path') or '-'}` |",
        f"| Model package | `{info.get('modelPackageId')}` v{info.get('modelVersion')} · {human(info.get('modelSizeBytes'))} |",
        f"| glTF files | {len(gltf)} |",
        f"| Texture pipeline | **{plabel}** |",
        f"| BaseColor images to paint | {len(paint)} |",
        f"| Entries in the official livery package | {len(everything)} |",
        f"| Livery packages | {len(liveries)} named + {len(generic)} generic |",
    ]
    if cfg:
        lines.append(f"| Configuration package | `{cfg.get('packageId')}` · {human(cfg.get('sizeBytes'))} |")
    if sample.get("name"):
        lines.append(f"| Sample livery parsed | {sample['name']} → `{sample.get('path')}`"
                     f"{' (Pro-only)' if sample.get('isProOnly') else ''} |")
    lines += ["", f"> {ptext}", ""]

    # 1. inventory
    lines += ["## 1. Inventory of one official package", ""]
    if inv_source == "livery":
        lines.append("These are the exact entries that livery package ships, at their real dimensions. The")
        lines.append("`paint` column marks the baseColor images — the ones you actually draw. Everything")
        lines.append("else is a PBR companion (`_ORM`, `_comp`, `_norm`, `_emis`) that must be present so the")
        lines.append("material does not fall back to a default channel value.")
    elif inv_source == "shared":
        lines.append("The per-livery package for this aircraft is metadata-only, so the inventory comes from")
        lines.append("the aircraft's shared texture set (`AircraftSharedLiveryFiles`) — the complete file list")
        lines.append("for the airframe, with real dimensions.")
    else:
        lines.append("No livery package could be parsed for this aircraft, so the inventory is the model's")
        lines.append("own `baseColor` reference set taken from its glTF. Dimensions are not available here.")
    lines += ["", "| file | dimensions | bytes | role | paint |", "|---|---|---|---|---|"]
    for f in sorted(everything, key=lambda x: x["name"].lower()):
        size = f.get("size")
        dim = f"{size[0]}×{size[1]}" if size else "?"
        mark = "**yes**" if f["name"] in paint_names else "keep"
        lines.append(f"| `{f['name']}` | {dim} | {human(f.get('bytes'))} | {f.get('kind')} | {mark} |")
    lines.append("")

    # 2. every baseColor
    lines += ["## 2. Every baseColor texture the model references", "",
              f"The {len(gltf)} glTF file(s) reference {len(base_colors)} distinct baseColor images in total.",
              "Cockpit, glass, pilot and interior materials are included here for completeness — repainting",
              "them changes the cockpit, not the airframe.", "", "```"]
    lines += base_colors or ["(none recorded)"]
    lines += ["```", ""]

    if gltf:
        lines += ["## 3. glTF files inside the model package", "", "```"]
        lines += gltf
        lines += ["```", ""]

    # 4. directories
    lines += [f"## 4. Livery directories ({len(dirs_named)})", "",
              "The directory name is `Path.GetFileName(LiveryPackage.Path)` — **not** what the app shows.",
              ""]
    if dirs_named:
        lines += ["| shown as | directory on disk |", "|---|---|"]
        for display, directory in dirs_named:
            lines.append(f"| {display} | `{directory}` |")
        if generic:
            lines += ["", "Generic packages: " + ", ".join(
                f"{g.get('name')} → `{livery_dir(g.get('path'))}`" for g in generic)]
    else:
        lines.append("No named liveries ship with this aircraft; only the Generic package exists.")
    lines.append("")

    # 5. package
    lines += ["## 5. Package it", "", "```bash", paint_cmd(repo, paint, extras), "```", "",
              "Resolves to, on Android:", "", "```",
              f"../../files/aircraft/{repo}/liveries/<livery directory>/<file name>", "```", "",
              "On iOS the root differs — replace `files` with `Library/dlc`:", "", "```",
              f"../../Library/dlc/aircraft/{repo}/liveries/<livery directory>/<file name>", "```", ""]

    # 6. import
    lines += ["## 6. Import", "", "```bash",
              f"adb push out/{slug(repo)}.zip /sdcard/Download/{slug(repo)}.zip",
              'adb shell "pm trim-caches <bytes>"   # only when repainting the same directory again',
              "```", "",
              "Then: **Scenery Editor → open an airport → Satellite → Import Imagery** → pick the zip,",
              "force-stop the app, reopen. Full walkthrough: [build-and-import.md](../build-and-import.md).",
              ""]

    (OUT / f"{slug(repo)}.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    rows.append((repo, name, plabel, len(paint), len(liveries), len(gltf), len(everything)))

# ---------- index ----------
lines = [
    "# Aircraft index",
    "",
    f"{len(rows)} aircraft, every one parsed from the live package catalog: its model package",
    "(for the glTF texture references) and one of its official livery packages (for the file",
    "inventory and dimensions). Nothing in these pages is inferred from a file name.",
    "",
    "| aircraft | repo | pipeline | paint | liveries | glTF | pkg entries |",
    "|---|---|---|---|---|---|---|",
]
for repo, name, plabel, npaint, nlivery, ngltf, nentries in rows:
    lines.append(f"| [{name}]({slug(repo)}.md) | `{slug(repo)}` | {plabel} | {npaint} | {nlivery} | {ngltf} | {nentries} |")

lines += ["", "## Pipeline breakdown", ""]
for kind, count in kinds_counter.most_common():
    lines.append(f"- **{kind}** — {count} aircraft")

lines += [
    "",
    "## Regenerate this data",
    "",
    "```bash",
    "python tools/fetch_catalog.py --dump-json data/catalog.json",
    "python tools/extract_models.py --catalog data/catalog.json",
    "python tools/extract_liveries.py --catalog data/catalog.json --type AircraftLivery --pick largest",
    "python tools/build_docs.py",
    "```",
    "",
    "`--pick largest` matters: many per-livery packages are 0-byte metadata-only updates, so picking the",
    "smallest one yields an empty inventory. See [../data-provenance.md](../data-provenance.md).",
    "",
]
(OUT / "index.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

print(f"wrote {len(rows)} aircraft pages + index.md")
print("pipelines:", dict(kinds_counter))
